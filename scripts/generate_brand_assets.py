"""
Generate brand assets from user-supplied logo.png and logo1.png.
Follows plan.md S2 and §5.8:
- logo.png produces favicon, apple-touch-icon, app icon, Android launcher icons
- logo1.png composited onto #080808 produces wordmark, OG image, and brand visuals
"""
import os
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BRAND_SRC = ROOT / "media" / "brand"
PUB_BRAND = ROOT / "public" / "brand"
APP_DIR = ROOT / "app"
PUB_DIR = ROOT / "public"

PUB_BRAND.mkdir(parents=True, exist_ok=True)

logo_path = BRAND_SRC / "logo.png"
logo1_path = BRAND_SRC / "logo1.png"

# Load sources
logo_img = Image.open(logo_path).convert("RGBA")
logo1_img = Image.open(logo1_path).convert("RGBA")

# 1. Favicon, Apple icon, App icon from logo.png
icon_512 = logo_img.resize((512, 512), Image.Resampling.LANCZOS)
icon_512.save(APP_DIR / "icon.png")

icon_180 = logo_img.resize((180, 180), Image.Resampling.LANCZOS)
icon_180.save(APP_DIR / "apple-icon.png")

icon_32 = logo_img.resize((32, 32), Image.Resampling.LANCZOS)
icon_32.save(PUB_DIR / "favicon.ico", format="ICO")

# 2. Wordmark on #080808
bg_color = (8, 8, 8, 255)
wordmark_bg = Image.new("RGBA", logo1_img.size, bg_color)
wordmark_bg.paste(logo1_img, (0, 0), logo1_img)
wordmark_bg.save(PUB_BRAND / "wordmark.png")
wordmark_bg.save(PUB_BRAND / "logo1-composite.png")

# Also copy raw source logos to public/brand
logo_img.save(PUB_BRAND / "logo.png")
logo1_img.save(PUB_BRAND / "logo1.png")

# 3. OG Image (1200 x 630) with logo1 composited on #080808
og_img = Image.new("RGBA", (1200, 630), bg_color)
# Scale logo1 to fit nicely within 900w x 450h
scale = min(900 / logo1_img.width, 450 / logo1_img.height)
new_w = int(logo1_img.width * scale)
new_h = int(logo1_img.height * scale)
logo1_scaled = logo1_img.resize((new_w, new_h), Image.Resampling.LANCZOS)
paste_x = (1200 - new_w) // 2
paste_y = (630 - new_h) // 2
og_img.paste(logo1_scaled, (paste_x, paste_y), logo1_scaled)
og_img.convert("RGB").save(PUB_BRAND / "og-image.png")

# 4. Android icons
res_dir = ROOT / "android" / "app" / "src" / "main" / "res"
if res_dir.exists():
    densities = {
        "mipmap-mdpi": 48,
        "mipmap-hdpi": 72,
        "mipmap-xhdpi": 96,
        "mipmap-xxhdpi": 144,
        "mipmap-xxxhdpi": 192,
    }
    for folder, size in densities.items():
        target_dir = res_dir / folder
        target_dir.mkdir(parents=True, exist_ok=True)
        # Adaptive safe-zone: logo occupies 66% of the icon, centered on #080808
        adaptive = Image.new("RGBA", (size, size), bg_color)
        inner_size = int(size * 0.72)
        inner_logo = logo_img.resize((inner_size, inner_size), Image.Resampling.LANCZOS)
        offset = (size - inner_size) // 2
        adaptive.paste(inner_logo, (offset, offset), inner_logo)
        adaptive.save(target_dir / "ic_launcher.png")
        adaptive.save(target_dir / "ic_launcher_round.png")

    # Store 512x512 icon for Android store listing
    icon_512.save(ROOT / "android" / "ic_launcher-playstore.png")

# 5. Write provenance documentation
provenance_doc = f"""# Brand Asset Provenance

Generated in accordance with DRISHYAM Master Specification §2.2 and §5.8.
The user-supplied logos are used directly as authoritative masters and are never regenerated by AI.

## Master Source Files
- `media/brand/logo.png`: 1254x1254 RGBA square app icon.
- `media/brand/logo1.png`: 1536x1024 RGBA full logo with wordmark.

## Derived Outputs
1. **Web App Favicons & Icons**:
   - `app/icon.png`: 512x512 Lanczos downscaled from `logo.png`.
   - `app/apple-icon.png`: 180x180 Lanczos downscaled from `logo.png`.
   - `public/favicon.ico`: 32x32 standard Windows/Web ICO from `logo.png`.
2. **Branding & Social**:
   - `public/brand/wordmark.png`: `logo1.png` composited cleanly onto `#080808`.
   - `public/brand/og-image.png`: 1200x630 OpenGraph social card on `#080808`.
3. **Android Application**:
   - `android/app/src/main/res/mipmap-*/ic_launcher.png`: Adaptive icons with safe zone on `#080808`.
   - `android/ic_launcher-playstore.png`: 512x512 Play Store icon.
"""
(BRAND_SRC / "README.md").write_text(provenance_doc, encoding="utf-8")
print("Brand assets generated successfully with full provenance.")
